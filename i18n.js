export function resolveLocale(preferences = []) {
  for (const preference of preferences) {
    if (typeof preference !== "string") continue;
    const locale = preference.toLowerCase().split(/[-_]/)[0];
    if (Object.hasOwn(translations, locale)) return locale;
  }
  return "en";
}

export function createI18n(initialLocale = "en") {
  let locale;
  let pluralRules;
  let numberFormat;

  function setLocale(nextLocale) {
    locale = resolveLocale([nextLocale]);
    pluralRules = new Intl.PluralRules(locale);
    numberFormat = new Intl.NumberFormat(locale);
  }

  setLocale(initialLocale);

  return {
    get locale() { return locale; },
    setLocale,
    t(key, values = {}) {
      let message = translations[locale][key] ?? translations.en[key];
      if (message === undefined) throw new Error(`Unknown translation: ${key}`);
      if (typeof message === "object") {
        message = message[pluralRules.select(values.count)] ?? message.other;
      }
      return message.replace(/\{(\w+)\}/g, (placeholder, name) => {
        const value = values[name];
        if (typeof value === "number") return numberFormat.format(value);
        return value ?? placeholder;
      });
    }
  };
}
